export const translations = { en, sw }

export function localeFor(language) {
  return LANGUAGES.find((entry) => entry.value === language)?.locale ?? 'en-GB'
}

export function translate(language, key, vars = {}) {
  const dictionary = translations[language] ?? translations.en
  const template = dictionary[key] ?? translations.en[key] ?? key
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (
    vars[name] === undefined || vars[name] === null ? match : String(vars[name])
  ))
}

export function createTranslator(language) {
  return (key, vars) => translate(language, key, vars)
}

export function translationKeys() {
  return {
    en: Object.keys(en).sort(),
    sw: Object.keys(sw).sort(),
  }
}

export function missingTranslationKeys() {
  const enKeys = new Set(Object.keys(en))
  const swKeys = new Set(Object.keys(sw))
  return {
    missingInSwahili: [...enKeys].filter((key) => !swKeys.has(key)),
    missingInEnglish: [...swKeys].filter((key) => !enKeys.has(key)),
  }
}
